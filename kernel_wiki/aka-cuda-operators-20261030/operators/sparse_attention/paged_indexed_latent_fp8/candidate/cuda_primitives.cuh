__device__ __forceinline__ bool s4_split_has_work(unsigned work, int groups,
        const int* seq, const int* lens, int topk) {
    unsigned query=work/(groups*8U), split=work%8U;
    int active=max(0,min(topk,lens ? min(seq[query],lens[query]) : seq[query]));
    int tiles=(active+127)/128, chunk=(tiles+7)/8;
    return split*chunk < tiles;
}

__device__ __forceinline__ void mbarrier_wait_token(int mbar_addr, int phase, uint32_t token) {
    if (token == 0) {
        mbarrier_wait(mbar_addr, phase);
    }
}

__device__ __forceinline__ float row_max_reduce(float2 acc) {
    return max_noftz(acc.x, acc.y);
}

__device__ __forceinline__ void row_max_x32_accum(const float* sv, float2& acc) {
    #pragma unroll
    for (int j = 0; j < 16; j++) {
        if (j % 2 == 0)
            acc.x = max_noftz(acc.x, max_noftz(sv[j*2], sv[j*2+1]));
        else
            acc.y = max_noftz(acc.y, max_noftz(sv[j*2], sv[j*2+1]));
    }
}

