__device__ __forceinline__ void s4_probability_mass4(uint32_t packed, float* dst) {
    uint16_t lo=static_cast<uint16_t>(packed), hi=static_cast<uint16_t>(packed>>16);
    asm volatile("{\n\t"
        ".reg .b32 x,y; .reg .b16 a,b,c,d;\n\t"
        "cvt.rn.f16x2.e4m3x2 x, %4;\n\t"
        "cvt.rn.f16x2.e4m3x2 y, %5;\n\t"
        "mov.b32 {a,b}, x; mov.b32 {c,d}, y;\n\t"
        "cvt.f32.f16 %0,a; cvt.f32.f16 %1,b;\n\t"
        "cvt.f32.f16 %2,c; cvt.f32.f16 %3,d;\n\t"
        "}" : "=f"(dst[0]),"=f"(dst[1]),"=f"(dst[2]),"=f"(dst[3]) : "h"(lo),"h"(hi));
}

