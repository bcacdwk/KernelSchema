"""Variant contracts and local CUDA compilation; dependency link order is explicit."""

import functools
import hashlib
import json
import os
from pathlib import Path
import subprocess
import torch

ROOT = Path(__file__).resolve().parent


def get_compute_capability(device):
    return torch.cuda.get_device_capability(device)


def get_cake_dsv4_spec(variant, *, arch):
    try:
        return _ARCH_REGISTRATIONS[arch]["variants"][variant]
    except KeyError as exc:
        raise ValueError("Unsupported variant: " + arch + "/" + variant) from exc


@functools.cache
def _source_identity():
    return {
        p.name: hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(ROOT.iterdir())
        if p.is_file()
    }


@functools.cache
def _load_dsv4(name, arch):
    from torch.utils import cpp_extension
    import tvm_ffi.libinfo

    contract = _ARCH_REGISTRATIONS[arch]["variants"][name]
    assert contract["arch"] == arch
    dependencies = [_load_dsv4(v, arch)[0] for v in contract.get("dependencies", [])]
    flags = CUDA_FLAGS + [
        "-gencode=arch=compute_" + arch[3:] + ",code=" + arch,
        *contract["compile_flags"],
        *contract.get("host_linkage_flags", []),
    ]
    compiler = subprocess.check_output(
        [str(Path(cpp_extension.CUDA_HOME) / "bin/nvcc"), "--version"], text=True
    )
    identity = [
        _source_identity(),
        contract,
        flags,
        compiler,
        torch.__version__,
        torch.version.cuda,
        tvm_ffi.__version__,
        dependencies,
    ]
    key = hashlib.sha256(json.dumps(identity, sort_keys=True).encode()).hexdigest()[:24]
    build = Path(
        os.environ.get("AKA_SF_BUILD_CACHE", Path.home() / ".cache/aka-candidates")
    ) / ("dual_cache_latent_fp8_" + key)
    build.mkdir(parents=True, exist_ok=True)
    ldflags = ["-lcuda"]
    if dependencies:
        ldflags = [
            "-Wl,--no-as-needed",
            *dependencies,
            "-Wl,--as-needed",
            "-lcuda",
            *["-Wl,-rpath," + str(Path(p).parent) for p in dependencies],
        ]
    library = cpp_extension.load(
        name="aka_dsv4_" + key,
        sources=[str(ROOT / p) for p in contract["sources"]],
        extra_cuda_cflags=flags,
        extra_cflags=["-O3", "-std=c++17"],
        extra_include_paths=[
            str(ROOT),
            tvm_ffi.libinfo.find_include_path(),
            tvm_ffi.libinfo.find_dlpack_include_path(),
        ],
        extra_ldflags=ldflags,
        build_directory=str(build),
        is_python_module=False,
        verbose=False,
    )
    return (library, tvm_ffi.load_module(library))


def get_cake_dsv4_module(variant, *, arch):
    return _load_dsv4(variant, arch)[1]


