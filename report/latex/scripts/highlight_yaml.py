#!/usr/bin/env python3
"""Color YAML verbatim blocks without changing body.tex or requiring shell-escape."""
from pathlib import Path
import argparse
import re
from io import StringIO
from pygments import format as pygments_format
from pygments.lexers import YamlLexer
from pygments.formatters import LatexFormatter
from pygments.style import Style
from pygments.token import Token, Comment, Name, String, Number, Keyword, Punctuation, Error

ROOT = Path(__file__).resolve().parents[1]
class ReportYamlStyle(Style):
    default_style = ''
    styles = {
        Token: '#243746',
        Comment: '#71808C',
        Name.Tag: 'bold #176B93',
        Name.Label: '#8154A3',
        Name.Variable: '#8154A3',
        String: '#168077',
        Number: '#A55B1C',
        Keyword: 'bold #8154A3',
        Punctuation: '#617785',
        Error: '#243746',
    }

PATTERN = re.compile(r'\\begin\{Verbatim\}\[([^\n]*)\]\n(.*?)\\end\{Verbatim\}', re.S)
NUMBER = re.compile(r'[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?\Z')

def render(source: str):
    formatter = LatexFormatter(style=ReportYamlStyle, commandprefix='YAML',
        verboptions='breaklines,breakanywhere,breaksymbolleft={},breaksymbolright={},breakautoindent=true')
    count = 0
    def replace(match):
        nonlocal count
        code = match.group(2)
        tokens = list(YamlLexer(stripnl=False, ensurenl=False).get_tokens(code))
        assert ''.join(value for _, value in tokens) == code, 'Lexer modified source'
        colored = []
        for kind, value in tokens:
            if (kind in Token.Literal and kind not in String) or kind in Name.Variable:
                if NUMBER.fullmatch(value): kind = Number
                elif value.lower() in {'true','false','null','~'}: kind = Keyword.Constant
            colored.append((kind, value))
        out = StringIO()
        pygments_format(colored, formatter, out)
        count += 1
        return out.getvalue().rstrip('\n')
    result = PATTERN.sub(replace, source)
    assert count > 0, 'No YAML Verbatim blocks found'
    return result, formatter.get_style_defs(), count

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--directory', type=Path, default=ROOT)
    args = parser.parse_args()
    body = args.directory / 'body.tex'
    result, style, count = render(body.read_text())
    outputs = {
        'body-highlighted.tex': '% Generated from body.tex; edit body.tex, then rebuild.\n' + result,
        'yaml-style.tex': '% Generated by scripts/highlight_yaml.py\n' + style,
    }
    for name, text in outputs.items():
        path = args.directory / name
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
    print(f'Highlighted {count} YAML blocks; token text preserved exactly.')
if __name__ == '__main__': main()
