#!/usr/bin/env python3
"""Deterministic, source-preserving Markdown -> report body converter.

Requires markdown-it-py. Never writes diagrams or modifies the Markdown source.
Unknown token types fail closed rather than silently dropping their content.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil

from markdown_it import MarkdownIt

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "old" / "基于 Schema 的 Kernel 表示与生成.md"
ORIGINAL_SHA256 = "6f592ed1fb8d0d3cb31856e16aceb649fd2a8cde0a63a97a3fed073e954053a8"
ESCAPES = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def escape(text: str) -> str:
    return "".join(ESCAPES.get(c, c) for c in text)


def prose(text: str) -> str:
    # The source has redundant ** delimiters next to code/emphasis spans.
    # Only presentation delimiters are removed; all words/punctuation survive.
    text = text.replace("**", "")
    parts = re.split(r"(\$[^$\n]+\$)", text)
    return "".join(p if p.startswith("$") and p.endswith("$") else escape(p).replace("↔", r"\(\leftrightarrow\)") for p in parts)


def inline(children) -> str:
    out = []
    for t in children or []:
        if t.type == "text":
            out.append(prose(t.content))
        elif t.type == "code_inline":
            # Explicit break opportunities after punctuation, never added glyphs.
            code = "".join(escape(c) + (r"\allowbreak{}" if c in "_/.-" else "") for c in t.content)
            out.append(r"\InlineCode{" + code + "}")
        elif t.type in {"strong_open", "em_open"}:
            out.append(r"\textbf{" if t.type == "strong_open" else r"\emph{")
        elif t.type in {"strong_close", "em_close"}:
            out.append("}")
        elif t.type == "softbreak":
            out.append(r"\\" + "\n")
        elif t.type == "hardbreak":
            out.append(r"\\" + "\n")
        elif t.type == "link_open":
            out.append(r"\href{" + escape(t.attrGet("href")) + "}{")
        elif t.type == "link_close":
            out.append("}")
        else:
            raise ValueError(f"Unsupported inline token: {t.type}: {t.content}")
    return "".join(out)


def convert(source: Path, copy_assets: bool):
    raw = source.read_bytes()
    sha = hashlib.sha256(raw).hexdigest()
    ts = MarkdownIt("commonmark").enable("table").parse(raw.decode("utf-8"))
    out = ["% Generated by scripts/convert.py; edit the Markdown source, then regenerate.", f"% Source SHA256: {sha}"]
    manifest = {"source_sha256": sha, "original_sha256_matches": sha == ORIGINAL_SHA256, "headings": [], "images": [], "diagrams": [], "yaml": [], "table_cells": [], "inline_blocks": []}
    # Cover reuses the original h1 plus the entire opening quotation.
    assert ts[0].type == "heading_open" and ts[0].tag == "h1"
    title = inline(ts[1].children)
    assert ts[3].type == "blockquote_open"
    end = next(i for i in range(4, len(ts)) if ts[i].type == "blockquote_close")
    cover = [inline(t.children) for t in ts[4:end] if t.type == "inline"]
    out += [r"\ReportCover{" + title + "}{" + r"\par ".join(cover) + "}", r"\ReportContents"]
    manifest["headings"].append(ts[1].content)
    manifest["inline_blocks"].extend(t.content for t in ts[:end+1] if t.type == "inline")
    i = end + 1
    diagram = 0
    while i < len(ts):
        t = ts[i]
        if t.type == "heading_open":
            level = int(t.tag[1:])
            command = {2: "section", 3: "subsection", 4: "subsubsection"}[level]
            if level == 2:
                out.append(r"\clearpage")
            if level == 4:
                out.append(r"\Needspace{6\baselineskip}")
            out.append(f"\\{command}{{{inline(ts[i+1].children)}}}")
            manifest["headings"].append(ts[i+1].content)
            manifest["inline_blocks"].append(ts[i+1].content)
            i += 3
            continue
        if t.type == "table_open":
            j = i + 1
            rows = []
            row = None
            while ts[j].type != "table_close":
                if ts[j].type == "tr_open":
                    row = []
                elif ts[j].type == "inline":
                    row.append(ts[j])
                    manifest["table_cells"].append(ts[j].content)
                elif ts[j].type == "tr_close":
                    rows.append(row)
                j += 1
            headers = rows[0]
            for row in rows[1:]:
                assert len(row) == len(headers)
                out.append(r"\begin{RouteCard}")
                for h, cell in zip(headers, row):
                    out.append(r"\CardField{" + inline(h.children) + "}{" + inline(cell.children) + "}")
                out.append(r"\end{RouteCard}")
            i = j + 1
            continue
        if t.type == "paragraph_open" and ts[i+1].type == "inline" and any(c.type == "image" for c in ts[i+1].children or []):
            img = ts[i+1].children
            assert len(img) == 1 and img[0].type == "image", "Mixed image/text paragraph needs explicit handling"
            img = img[0]
            original = (SOURCE.parent / img.attrGet("src")).resolve()
            name = original.name
            if copy_assets:
                ROOT.joinpath("assets").mkdir(exist_ok=True)
                target = ROOT / "assets" / name
                if not target.exists() or target.read_bytes() != original.read_bytes():
                    shutil.copy2(original, target)
            manifest["images"].append({"source": img.attrGet("src"), "asset": name, "alt": img.content, "sha256": hashlib.sha256(original.read_bytes()).hexdigest()})
            # Original Markdown captions directly following images stay attached.
            j = i + 3
            caption = ""
            if j < len(ts) and ts[j].type == "blockquote_open":
                k = next(k for k in range(j+1, len(ts)) if ts[k].type == "blockquote_close")
                inside = [x for x in ts[j:k] if x.type == "inline"]
                caption = r"\par ".join(inline(x.children) for x in inside)
                manifest["inline_blocks"].extend(x.content for x in inside)
                j = k + 1
            command = "TallOriginalImage" if name == "root.png" else "OriginalImage"
            if level == 4:
                out.append(r"\Needspace{6\baselineskip}")
            out.append(f"\\{command}{{assets/{name}}}{{{escape(img.content)}}}{{{caption}}}")
            i = j
            continue
        if t.type == "fence":
            if t.info.strip() == "mermaid":
                diagram += 1
                path = f"diagrams/diagram-{diagram:02d}.tex"
                manifest["diagrams"].append({"number": diagram, "lines": t.map, "sha256": hashlib.sha256(t.content.encode()).hexdigest()})
                out.extend([r"\begin{DiagramBlock}", f"\\IfFileExists{{{path}}}{{%", r"\begin{adjustbox}{max width=\linewidth,max totalheight=.80\textheight,center}", f"\\input{{{path}}}%", r"\end{adjustbox}%", "}{%", f"\\MissingDiagram{{{diagram:02d}}}%", "}", r"\end{DiagramBlock}"])
            else:
                assert t.info.strip() == "yaml", f"Unrecognized fence: {t.info}"
                manifest["yaml"].append(t.content)
                out.extend([r"\begin{CodeBox}", r"\begin{Verbatim}[breaklines,breakanywhere,breaksymbolleft={},breaksymbolright={},breakautoindent=true]", t.content.rstrip("\n"), r"\end{Verbatim}", r"\end{CodeBox}"])
        elif t.type == "inline":
            out.append(inline(t.children))
            manifest["inline_blocks"].append(t.content)
        elif t.type == "paragraph_open":
            pass
        elif t.type == "paragraph_close":
            out.append("\n")
        elif t.type == "hr":
            out.append(r"\SourceSeparator")
        elif t.type == "bullet_list_open":
            out.append(r"\begin{itemize}")
        elif t.type == "bullet_list_close":
            out.append(r"\end{itemize}")
        elif t.type == "ordered_list_open":
            out.append(r"\begin{enumerate}[start=" + str(t.attrGet("start") or 1) + "]")
        elif t.type == "ordered_list_close":
            out.append(r"\end{enumerate}")
        elif t.type == "list_item_open":
            out.append(r"\item")
        elif t.type == "list_item_close":
            pass
        elif t.type == "blockquote_open":
            out.append(r"\begin{ReportQuote}")
        elif t.type == "blockquote_close":
            out.append(r"\end{ReportQuote}")
        else:
            raise ValueError(f"Unsupported block token {t.type}: {t.content}")
        i += 1
    assert diagram == 13, f"Expected 13 Mermaid positions, found {diagram}"
    assert len(manifest["images"]) == 7
    assert len(manifest["yaml"]) == 3
    assert len(manifest["table_cells"]) == 20
    expected_inlines = sum(t.type == "inline" for t in ts)
    accounted = len(manifest["inline_blocks"]) + len(manifest["table_cells"]) + len(manifest["images"])
    assert expected_inlines == accounted, (expected_inlines, accounted)
    body = "\n".join(out) + "\n"
    # Verbatim payloads must remain byte-for-byte intact, including indentation.
    emitted_yaml = re.findall(r"\\begin\{Verbatim\}\[[^\n]*\]\n(.*?)\\end\{Verbatim\}", body, re.S)
    assert emitted_yaml == manifest["yaml"]
    manifest["inline_blocks_accounted"] = accounted
    manifest["body_sha256"] = hashlib.sha256(body.encode()).hexdigest()
    return body, manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--check", action="store_true", help="Read-only: verify body.tex is current and assets are exact copies")
    parser.add_argument("--manifest", type=Path, help="Optional audit JSON output (e.g. /tmp/kernel-report-manifest.json)")
    args = parser.parse_args()
    body, manifest = convert(args.source, not args.check)
    dest = ROOT / "body.tex"
    if args.check:
        if dest.read_text() != body:
            raise SystemExit("body.tex differs from deterministic conversion; run scripts/convert.py")
        for img in manifest["images"]:
            assert hashlib.sha256((ROOT / "assets" / img["asset"]).read_bytes()).hexdigest() == img["sha256"]
    else:
        dest.write_text(body)
    if args.manifest:
        args.manifest.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    print(f"{'Verified' if args.check else 'Converted'}: {len(manifest['headings'])} headings; {manifest['inline_blocks_accounted']} inline blocks; 20 table cells; 3 exact YAML blocks; 7 original images; 13 diagram inputs")
    print(f"Source SHA256: {manifest['source_sha256']}")


if __name__ == "__main__":
    main()
